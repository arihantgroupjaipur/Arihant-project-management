import claude from '../config/claude.js';
import { buildProgressReport } from './progressReportAggregator.js';
import { synthesizeSpeech } from './textToSpeech.js';
import { sendEmail, getEmailTemplate } from './emailService.js';
import ScheduledCeoReport from '../models/ScheduledCeoReport.js';

const MODEL = 'claude-sonnet-5';

// Asks Claude for a short spoken narration script (not JSON) — sized for ~1 minute of audio at natural speaking pace.
async function buildNarrationScript(report) {
    const response = await claude.messages.create({
        model: MODEL,
        max_tokens: 600,
        system: 'You are a construction project analyst preparing a short spoken audio briefing for a company CEO. ' +
            'Write ONLY the words to be spoken aloud — no headers, no markdown, no labels like "Summary:". ' +
            'Target exactly 140-160 words (about 1 minute at a natural speaking pace). ' +
            'Be direct and specific: name the contractors/site engineers who are lacking and why, using the real numbers given. ' +
            'End with one clear recommended next step. Never invent names or numbers not present in the data.',
        messages: [
            {
                role: 'user',
                content: `Write the CEO audio briefing script for this ${report.period} progress report (site: ${report.site || 'all sites'}, ${report.from} to ${report.to}, ${report.entryCount} entries).

Contractor performance:
${JSON.stringify(report.contractors, null, 2)}

Site engineer performance:
${JSON.stringify(report.engineers, null, 2)}`,
            },
        ],
    });
    const textBlock = response.content.find((b) => b.type === 'text');
    return (textBlock?.text ?? '').trim();
}

// Builds the report, generates the narration + audio, and emails it (with the wav attached) to the CEO.
export async function sendCeoAudioReport({ period, site, ceoEmail }) {
    if (!ceoEmail) throw new Error('CEO email is not configured');

    const report = await buildProgressReport({ period, site });

    if (report.entryCount === 0) {
        throw new Error('No progress data found for this period/site — nothing to report');
    }

    const script = await buildNarrationScript(report);
    const audioBuffer = await synthesizeSpeech(script);
    const audioBase64 = audioBuffer.toString('base64');

    const bodyHtml = `
        <p>Hi,</p>
        <p>Attached is a ~1 minute audio briefing on ${report.period} site progress (${report.from} to ${report.to}${report.site ? `, site: ${report.site}` : ''}), generated by AI from the daily progress reports.</p>
        <p style="white-space: pre-wrap; background:#f9fafb; border-left: 3px solid #dc2626; padding: 12px 16px; border-radius: 6px; font-size: 14px; color:#374151;">${script}</p>
        <p>Play the attached audio file for the full spoken briefing.</p>
    `;
    const html = getEmailTemplate('Site Progress Briefing', bodyHtml);

    const attachments = [{ name: `progress-briefing-${report.to}.wav`, content: audioBase64 }];

    await sendEmail(ceoEmail, `Site Progress Briefing — ${report.period} (${report.to})`, html, attachments);

    return { script, entryCount: report.entryCount };
}

// Finds due scheduled CEO reports (scheduledFor <= now, status pending) and sends them
export async function processDueScheduledCeoReports() {
    const due = await ScheduledCeoReport.find({ status: 'pending', scheduledFor: { $lte: new Date() } });
    for (const item of due) {
        try {
            await sendCeoAudioReport({ period: item.period, site: item.site, ceoEmail: item.ceoEmail });
            item.status = 'sent';
            item.sentAt = new Date();
            await item.save();
        } catch (error) {
            console.error(`Failed to send scheduled CEO report ${item._id}:`, error);
            item.status = 'failed';
            item.error = error.message;
            await item.save();
        }
    }
    return due.length;
}
